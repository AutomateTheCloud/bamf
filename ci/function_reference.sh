###------------------------------------------------------------------------------------------------
## Config
# shellcheck disable=SC2034 # read by bamf.inc
SELF_IDENTITY="function_reference"
# shellcheck disable=SC2034 # read by usage
ARGUMENTS_DESCRIPTION=(
    '-c : Check only: exit with E_CHECKSUM_MISMATCH if a reference is out of date (the default)'
    '-u : Update the references'
)

###------------------------------------------------------------------------------------------------
## Load Defaults
DIRECTORY_REPOSITORY="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=../bamf.inc
source "${DIRECTORY_REPOSITORY}/bamf.inc" || exit 3

###------------------------------------------------------------------------------------------------
## Variables
FILE_README="${DIRECTORY_REPOSITORY}/README.md"
MARKER_BEGIN="<!-- BEGIN FUNCTION REFERENCE -->"
MARKER_END="<!-- END FUNCTION REFERENCE -->"
MODE="check"

###------------------------------------------------------------------------------------------------
## Functions

## FUNCTION: markdown_cell()
## - Prints text made safe for a markdown table cell
## - Arguments
##   - $1: Text
function markdown_cell() {
    local TMP_TEXT="${1}"
    TMP_TEXT="${TMP_TEXT//|/\\|}"
    printf '%s' "${TMP_TEXT}"
}

## FUNCTION: reference_for_file()
## - Prints the markdown reference for one library file
## - Arguments
##   - $1: Library file
function reference_for_file() {
    local TMP_FILE="${1}"
    local TMP_LINE=""
    local TMP_NAME=""
    local TMP_SECTION=""
    local TMP_DESCRIPTION=""
    local TMP_ARGUMENTS=""
    local TMP_PURPOSE=""
    local -a TMP_ROWS=()

    return_header_string purpose "${TMP_FILE}" TMP_PURPOSE
    printf '### `%s`\n\n%s\n\n' "${TMP_FILE##*/}" "${TMP_PURPOSE}"
    printf '| Function | What it does | Arguments |\n|---|---|---|\n'

    while IFS= read -r TMP_LINE || [[ -n "${TMP_LINE}" ]]; do
        if [[ "${TMP_LINE}" =~ ^##\ FUNCTION:\ ([a-z][a-z_0-9]*)\(\)$ ]]; then
            TMP_NAME="${BASH_REMATCH[1]}"
            TMP_SECTION="description"
            TMP_DESCRIPTION=""
            TMP_ARGUMENTS=""
        elif [[ -z "${TMP_NAME}" ]]; then
            continue
        elif [[ "${TMP_LINE}" == "## - Arguments" ]]; then
            TMP_SECTION="arguments"
        elif [[ "${TMP_LINE}" =~ ^##\ -\ (.*)$ ]] && [[ "${TMP_SECTION}" == "description" ]]; then
            TMP_DESCRIPTION+="${TMP_DESCRIPTION:+<br>}$(markdown_cell "${BASH_REMATCH[1]}")"
        elif [[ "${TMP_LINE}" =~ ^##\ +-\ (\$[0-9]+\+?):\ (.*)$ ]] && [[ "${TMP_SECTION}" == "arguments" ]]; then
            TMP_ARGUMENTS+="${TMP_ARGUMENTS:+<br>}\`${BASH_REMATCH[1]}\` $(markdown_cell "${BASH_REMATCH[2]}")"
        elif [[ "${TMP_LINE}" =~ ^##\ +(.*)$ ]]; then
            # continuation of the previous line
            if [[ "${TMP_SECTION}" == "arguments" ]]; then
                TMP_ARGUMENTS+=" $(markdown_cell "${BASH_REMATCH[1]}")"
            else
                TMP_DESCRIPTION+=" $(markdown_cell "${BASH_REMATCH[1]}")"
            fi
        elif [[ "${TMP_LINE}" == "function ${TMP_NAME}()"* ]]; then
            TMP_ROWS+=( "$(printf '| `%s` | %s | %s |' "${TMP_NAME}" "${TMP_DESCRIPTION}" "${TMP_ARGUMENTS:-none}")" )
            TMP_NAME=""
        fi
    done < "${TMP_FILE}"
    printf '%s\n' "${TMP_ROWS[@]}" | LC_ALL=C sort -t '`' -k 2,2
    printf '\n'
}

###------------------------------------------------------------------------------------------------
## Main
while getopts "hVcu" OPTION; do
    case "${OPTION}" in
        c) MODE="check";;
        u) MODE="update";;
        h) usage; exit 0;;
        V) return_script_version "${0}"; printf '\n'; exit 0;;
        *) usage; exit "${E_BAD_ARGS}";;
    esac
done

start_logic

FILE_HELPERS_README="${DIRECTORY_REPOSITORY}/helpers/README.md"
OUT_OF_DATE=0

## update_reference <readme> <library files...>: replaces the text between the markers with the reference
function update_reference() {
    local TMP_README="${1}"
    local TMP_FILE_REFERENCE=""
    local TMP_FILE_README_NEW=""
    local TMP_LIBRARY=""
    shift
    generate_temp_file TMP_FILE_REFERENCE "generated reference"
    generate_temp_file TMP_FILE_README_NEW "updated README"
    {
        printf '%s\n\n' "${MARKER_BEGIN}"
        printf '<!-- Generated by ci/function_reference.sh from the FUNCTION comments in the code. Do not edit by hand. -->\n\n'
        for TMP_LIBRARY in "$@"; do
            reference_for_file "${TMP_LIBRARY}"
        done
        printf '%s\n' "${MARKER_END}"
    } > "${TMP_FILE_REFERENCE}"
    if ! grep -qxF "${MARKER_BEGIN}" "${TMP_README}" || ! grep -qxF "${MARKER_END}" "${TMP_README}"; then
        log_error "${TMP_README} does not contain the reference markers"
        exit_logic "${E_OBJECT_NOT_FOUND}"
    fi
    awk -v begin="${MARKER_BEGIN}" -v end="${MARKER_END}" -v reference="${TMP_FILE_REFERENCE}" '
        $0 == begin { while ((getline line < reference) > 0) print line; skip = 1; next }
        $0 == end   { skip = 0; next }
        !skip       { print }
    ' "${TMP_README}" > "${TMP_FILE_README_NEW}"
    if cmp -s "${TMP_README}" "${TMP_FILE_README_NEW}"; then
        log "- up to date: [${TMP_README#"${DIRECTORY_REPOSITORY}"/}]"
    elif [[ "${MODE}" == "update" ]]; then
        cat "${TMP_FILE_README_NEW}" > "${TMP_README}"
        log "- updated:    [${TMP_README#"${DIRECTORY_REPOSITORY}"/}]"
    else
        log_warning "- out of date: [${TMP_README#"${DIRECTORY_REPOSITORY}"/}]"
        OUT_OF_DATE=1
    fi
}

update_reference "${FILE_README}" "${DIRECTORY_REPOSITORY}/bamf.inc"
update_reference "${FILE_HELPERS_README}" "${DIRECTORY_REPOSITORY}"/helpers/bamf.*.inc

if (( OUT_OF_DATE == 0 )); then
    log_success "The function references are up to date"
    exit_logic 0
fi
log_error "The function references are out of date; run: ci/function_reference.sh -u"
exit_logic "${E_CHECKSUM_MISMATCH}"
